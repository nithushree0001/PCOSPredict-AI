
import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Her Cycle AI",
    page_icon="🌸",
    layout="wide"
)

# Load trained model
@st.cache_resource
def load_model():
    return joblib.load("pcos_random_forest.pkl")

try:
    model = load_model()
except Exception as e:
    st.error("Model not found. Keep pcos_random_forest.pkl in the same folder as shree.py.")
    st.stop()

# Page heading
st.title("🌸 Her Cycle AI")
st.subheader("Menstrual Health & PCOS Risk Screening")
st.write(
    "Enter your details below to receive a model-generated risk screening. "
    "This is not a medical diagnosis."
)

st.divider()

# User inputs
st.header("👩 Personal Details")

col1, col2, col3 = st.columns(3)

with col1:
    age = st.number_input("Age", 10, 60, 20)
    height = st.number_input("Height (cm)", 100.0, 220.0, 160.0)
    weight = st.number_input("Weight (kg)", 20.0, 200.0, 55.0)

with col2:
    cycle = st.number_input("Cycle Length (days)", 15, 60, 28)
    period = st.number_input("Period Duration (days)", 1, 15, 5)
    regularity = st.selectbox(
        "Period Regularity", ["Regular", "Irregular"]
    )

with col3:
    pain = st.selectbox(
        "Pain Level", ["Mild", "Moderate", "Severe"]
    )
    bleeding = st.selectbox(
        "Bleeding Level", ["Light", "Normal", "Heavy"]
    )
    pms = st.selectbox("PMS", ["Yes", "No"])

bmi = weight / ((height / 100) ** 2)
st.info(f"Calculated BMI: {bmi:.1f}")

st.header("🩷 Health Indicators")

col4, col5, col6 = st.columns(3)

with col4:
    acne = st.selectbox("Acne", ["No", "Yes"])
    hair_growth = st.selectbox("Excess Hair Growth", ["No", "Yes"])
    hair_loss = st.selectbox("Hair Loss", ["No", "Yes"])

with col5:
    weight_gain = st.selectbox("Recent Weight Gain", ["No", "Yes"])
    stress = st.selectbox(
        "Stress Level", ["Low", "Moderate", "High"]
    )
    sleep = st.number_input("Sleep Hours", 0.0, 24.0, 7.0)

with col6:
    exercise = st.selectbox(
        "Exercise Level", ["Low", "Moderate", "High"]
    )
    mood = st.selectbox("Mood Swings", ["No", "Yes"])
    abdominal = st.selectbox("Abdominal Pain", ["No", "Yes"])

# Optional feature used by some training datasets
st.header("📅 Period Information")
next_period = st.number_input(
    "Expected Days Until Next Period", 1, 60, 28
)

st.divider()

if st.button("🔍 Predict PCOS Risk", type="primary", use_container_width=True):

    # Match the columns used to train the model
    input_data = pd.DataFrame([{
        "Age": age,
        "Height_cm": height,
        "Weight_kg": weight,
        "BMI": bmi,
        "Cycle_Length_days": cycle,
        "Period_Duration_days": period,
        "Period_Regularity": regularity,
        "Pain_Level": pain,
        "Bleeding_Level": bleeding,
        "PMS": pms,
        "Acne": acne,
        "Excess_Hair_Growth": hair_growth,
        "Hair_Loss": hair_loss,
        "Weight_Gain": weight_gain,
        "Stress_Level": stress,
        "Sleep_Hours": sleep,
        "Exercise_Level": exercise,
        "Mood_Swings": mood,
        "Abdominal_Pain": abdominal,
        "Expected_Next_Period_Days": next_period
    }])

    try:
        # Reorder columns to match the training pipeline
        preprocessor = model.named_steps["preprocessor"]
        expected_columns = list(preprocessor.feature_names_in_)
        input_data = input_data.reindex(columns=expected_columns)

        prediction = model.predict(input_data)[0]

        st.subheader("🌸 Your Screening Result")

        if prediction == "Higher Risk":
            st.error(f"Result: {prediction}")
            st.write(
                "Consider consulting a qualified healthcare professional "
                "for an appropriate assessment."
            )
        elif prediction == "Moderate Risk":
            st.warning(f"Result: {prediction}")
            st.write(
                "If you have ongoing menstrual concerns, consider discussing "
                "them with a healthcare professional."
            )
        else:
            st.success(f"Result: {prediction}")
            st.write(
                "Continue monitoring your menstrual health and any symptoms."
            )

        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(input_data)[0]
            st.subheader("Prediction Confidence by Category")
            for label, probability in zip(model.classes_, probabilities):
                st.write(f"**{label}:** {probability * 100:.1f}%")
                st.progress(float(probability))

        st.caption(
            "This result is generated by a machine-learning model trained "
            "on your dataset. It cannot diagnose or rule out PCOS."
        )

    except Exception as e:
        st.error("Prediction failed. Check the model and input feature columns.")
        st.code(str(e))
